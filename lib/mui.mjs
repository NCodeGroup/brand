// Writes mui/instrument.json: what a Material UI theme needs from the tokens, as plain data. The theme itself, its
// createTheme call and its component overrides, belongs to the product that uses Material UI, under that product's
// type check and tests and tied to its Material UI major version (docs/decisions/1005).
import { entries, listTokens, resolveColors, resolveRole, valueOf } from './model.mjs';

const px = (css) => Number.parseFloat(css) * (css.endsWith('rem') ? 16 : 1);
const ms = (css) => Number.parseFloat(css);

/** Material UI's typography variants, each set in an Instrument type role. Variants not named keep their defaults. */
export const VARIANTS = {
  h1: 'title',
  h2: 'heading-long',
  h3: 'heading',
  h4: 'subheading',
  h5: 'subheading',
  h6: 'minor',
  subtitle1: 'minor',
  body1: 'ui',
  button: 'ui',
  overline: 'label',
  label: 'label',
  field: 'field',
  value: 'value',
  code: 'code',
  readout: 'readout',
};

/** Material UI's elevations 0 to 24, as Instrument's five depths. */
function shadows(tokens, theme) {
  const depth = Object.fromEntries(tokens.filter((t) => t.kind === 'shadow').map((t) => [t.path.split('.').at(-1), t[theme]]));
  return Array.from({ length: 25 }, (_, level) => {
    if (level === 0) return 'none';
    if (level < 4) return depth.flush;
    if (level < 8) return depth.raised;
    return level < 16 ? depth.floating : depth.overlay;
  });
}

function palette(model, theme) {
  const c = resolveColors(model, theme);
  const tone = (main, dark, on) => ({ main: c[main], dark: c[dark], contrastText: c[on] });
  return {
    mode: theme,
    primary: tone('primary', 'primary-hover', 'on-primary'),
    error: tone('danger', 'danger-hover', 'on-danger'),
    warning: { main: c.warning, contrastText: c['on-warning'] },
    info: { main: c.info, contrastText: c['on-info'] },
    success: { main: c.success, contrastText: c['on-success'] },
    background: { default: c.page, paper: c.surface },
    text: { primary: c.text, secondary: c['text-secondary'], disabled: c['text-disabled'] },
    divider: c.border,
    instrument: c,
  };
}

export function muiData(model, version) {
  const tokens = listTokens(model);
  const value = (path) => tokens.find((t) => t.path === path).light;
  const role = (name) => resolveRole(model, model.source.semantic.type[name]);
  const variants = Object.fromEntries(Object.entries(VARIANTS).map(([variant, name]) => {
    const r = role(name);
    const style = { role: name, ...r, fontFamily: r.fontFamily.map((f) => (/^[a-z-]+$/.test(f) ? f : `"${f}"`)).join(', ') };
    if (variant === 'button') Object.assign(style, { fontWeight: valueOf(model.source.base.font.weight.semibold), textTransform: 'none', lineHeight: 1 });
    if (model.source.semantic.type[name].family === 'mono') style.fontFeatureSettings = '"zero" 1';
    return [variant, style];
  }));
  const family = (name) => valueOf(model.source.base.font.family[name]).map((f) => (/^[a-z-]+$/.test(f) ? f : `"${f}"`)).join(', ');
  return {
    $description:
      `What a Material UI theme takes from NCode Brand ${version}, as plain data. "palette" holds Material UI's palette ` +
      "colors for NCode's own brand, and under \"instrument\" every semantic color role by its token name; " +
      "tokens/derive.mjs derives a tenant's. \"typography.variants\" sets each named variant in an Instrument type role. " +
      '"shadows" maps the 25 elevations onto the five depths. "spacing" is 8, the unit Material UI layouts are written ' +
      'in; "space" is Instrument\'s scale. The focus ring is "focus" wide and offset, in the color instrument.focus. ' +
      'Lengths are in pixels and durations in milliseconds. Generated by build.mjs from src/tokens.source.json; do not ' +
      'edit it.',
    version,
    palette: { light: palette(model, 'light'), dark: palette(model, 'dark') },
    typography: {
      fontFamily: family('sans'),
      fontFamilyMono: family('mono'),
      fontSize: px(value('font.size.md')),
      fontWeightRegular: valueOf(model.source.base.font.weight.regular),
      fontWeightMedium: valueOf(model.source.base.font.weight.medium),
      fontWeightBold: valueOf(model.source.base.font.weight.bold),
      variants,
    },
    shape: { borderRadius: px(value('radius.control')) },
    radius: Object.fromEntries(entries(model.source.base.radius).map(([name]) => [name, px(value(`radius.${name}`))])),
    spacing: 8,
    space: Object.fromEntries(entries(model.source.base.space).map(([name]) => [name, px(value(`space.${name}`))])),
    size: Object.fromEntries(entries(model.source.base.size).map(([name]) => [name, px(value(`size.${name}`))])),
    shadows: { light: shadows(tokens, 'light'), dark: shadows(tokens, 'dark') },
    transitions: {
      duration: Object.fromEntries(entries(model.source.base.motion.duration).map(([name]) => [name, ms(value(`duration.${name}`))])),
      easing: Object.fromEntries(entries(model.source.base.motion.easing).map(([name]) => [name, value(`easing.${name}`)])),
    },
    breakpoints: Object.fromEntries(entries(model.source.base.breakpoint).map(([name]) => [name, px(value(`breakpoint.${name}`))])),
    focus: { width: px(value('size.focus-width')), offset: px(value('size.focus-gap')) },
  };
}
