// Writes syntax/instrument-screen.json: the syntax theme of a code block on a screen, as a VS Code color theme that
// Expressive Code loads. Each scope's color is the var() of a screen role that the .tk-* classes of src/css/base.css
// use (docs/decisions/1012).
import { PREFIX, resolveColors } from './model.mjs';

/**
 * The TextMate scopes each screen role colors, in the order the theme lists them. The last rule exists because a
 * command's arguments are not literal values.
 */
export const RULES = [
  { role: 'on-screen-secondary', scope: ['source', 'text'] },
  { role: 'on-screen-muted', scope: ['comment', 'punctuation.definition.comment', 'string.comment'] },
  {
    role: 'screen-lit',
    scope: [
      'keyword',
      'storage',
      'storage.type',
      'storage.modifier',
      'keyword.operator.new',
      'keyword.operator.expression',
      'variable.language',
      'constant.language.null',
    ],
  },
  {
    role: 'on-screen',
    scope: [
      'entity.name.type',
      'entity.name.class',
      'entity.name.function',
      'entity.name.tag',
      'support.type',
      'support.class',
      'support.function',
      'meta.function-call.generic',
    ],
  },
  {
    role: 'screen-hot',
    scope: [
      'constant.numeric',
      'constant.language.boolean',
      'constant.language',
      'constant.character',
      'string',
      'string.quoted',
      'punctuation.definition.string',
    ],
  },
  { role: 'screen-lit', scope: ['entity.other.attribute-name'] },
  { role: 'on-screen', scope: ['string.unquoted', 'source.shell string.unquoted'] },
];

/** syntax/instrument-screen.json: a VS Code color theme whose token colors are the screen's color roles as var(). */
export function syntaxTheme(model, version) {
  const c = resolveColors(model, 'light');
  return {
    $schema: 'vscode://schemas/color-theme',
    $description:
      `The syntax theme of a code block on a screen, NCode Brand ${version}, as a VS Code color theme for Expressive ` +
      'Code. Each color is the var() of a screen role of tokens/tokens.css: keywords screen-lit, types and members ' +
      "on-screen, comments on-screen-muted, literals screen-hot and the rest on-screen-secondary. Load it on a page that " +
      "loads tokens/tokens.css, and turn off Expressive Code's contrast correction, which cannot compute with a " +
      'custom property. A screen is the same in both themes, so one theme serves both. editor.background and ' +
      "editor.foreground are the screen and its ink for NCode's own brand: Expressive Code reads them to load a " +
      'theme. Generated by build.mjs from src/tokens.source.json and lib/syntax.mjs; do not edit it.',
    name: 'instrument-screen',
    type: 'dark',
    colors: { 'editor.background': c.screen, 'editor.foreground': c['on-screen-secondary'] },
    tokenColors: RULES.map(({ role, scope }) => ({ scope, settings: { foreground: `var(${PREFIX}color-${role})` } })),
  };
}
