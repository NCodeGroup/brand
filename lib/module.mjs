// Writes tokens/tokens.mjs and tokens/tokens.d.mts: the public tokens as a typed ES module, every value resolved
// for NCode's own brand. Primitives are left out: they are private (docs/decisions/1002).
import { braceSizes, entries, listTokens, resolveRole, valueOf } from './model.mjs';

/** The module's exports, each a plain object of values, with a note per key where the source has one. */
export function moduleData(model, version) {
  const tokens = listTokens(model).filter((t) => t.tier === 'semantic');
  const byKind = (kind) => tokens.filter((t) => t.kind === kind);
  const keyOf = (token) => token.path.split('.').at(-1);
  const values = {};
  const notes = {};
  const put = (exportName, key, value, note) => {
    (values[exportName] ??= {})[key] = value;
    if (note) notes[`${exportName}.${key}`] = note;
  };
  values.version = version;
  for (const t of byKind('color-role')) {
    put('color', 'light', { ...(values.color?.light ?? {}), [t.path.slice(6)]: t.light });
    put('color', 'dark', { ...(values.color?.dark ?? {}), [t.path.slice(6)]: t.dark });
    if (t.note) notes[`color.*.${t.path.slice(6)}`] = t.note;
  }
  for (const t of byKind('shadow')) {
    put('elevation', 'light', { ...(values.elevation?.light ?? {}), [keyOf(t)]: t.light });
    put('elevation', 'dark', { ...(values.elevation?.dark ?? {}), [keyOf(t)]: t.dark });
  }
  for (const t of byKind('input')) put('input', keyOf(t), t.light, t.note);
  for (const [name, entry] of entries(model.source.base.font.family)) put('font', name, [...valueOf(entry)], entry.note);
  for (const [name, role] of entries(model.source.semantic.type)) put('type', name, resolveRole(model, role), role.note);
  for (const t of byKind('space')) put('space', keyOf(t), t.light, t.note);
  for (const t of byKind('radius')) put('radius', keyOf(t), t.light, t.note);
  for (const t of byKind('border')) put('border', keyOf(t), t.light, t.note);
  for (const t of byKind('size')) put('size', keyOf(t), t.light, t.note);
  for (const t of byKind('breakpoint')) put('breakpoint', keyOf(t), t.light, t.note);
  for (const t of byKind('duration')) put('duration', keyOf(t), t.light, t.note);
  for (const t of byKind('easing')) put('easing', keyOf(t), t.light, t.note);
  for (const size of braceSizes(model)) put('brace', size.name, { width: `${size.width}px`, minHeight: `${size.minHeight}px` }, size.note);
  values.property = Object.fromEntries(tokens.map((t) => [t.property.slice(2), t.property]));
  return { values, notes };
}

const DOCS = {
  version: 'The NCode Brand release these tokens came from.',
  color: "The color roles, resolved for NCode's own brand: tokens/derive.mjs derives a tenant's.",
  elevation: 'The five depths, as box-shadow values with their colors resolved.',
  input: "The tenant inputs' defaults: brand is NCode Blue, and brand-secondary follows it.",
  font: 'The two families, as font-family lists.',
  type: 'The type roles, every value resolved: the fields of a CSS style object.',
  space: 'The space scale.',
  radius: 'The radius of each kind of part.',
  border: 'The two line widths.',
  size: 'The measures two parts must agree on.',
  breakpoint: 'Where a layout changes.',
  duration: 'How long each kind of motion takes.',
  easing: 'How each kind of motion moves.',
  brace: 'Each stretching brace: its width, and the least height it draws at.',
  property: 'Every public token\'s custom property, by its name without the leading "--".',
};

export function tokensModule(model, version) {
  const { values } = moduleData(model, version);
  const lines = [
    '/*',
    ` * ${model.source.name}: NCode's public design tokens as an ES module, NCode Brand ${version}. Every value is`,
    " * resolved for NCode's own brand, light and dark. tokens.d.mts types it.",
    ' *',
    ' * Generated by build.mjs from src/tokens.source.json: do not edit it. Licensed under the Apache License 2.0.',
    ' */',
    '',
  ];
  for (const [name, value] of Object.entries(values)) {
    lines.push(`/** ${DOCS[name]} */`, `export const ${name} = ${JSON.stringify(value, null, 2)};`, '');
  }
  return lines.join('\n');
}

/** A TypeScript type for a JSON value: readonly objects and arrays, plain string and number leaves. */
function typeOf(value, indent, path, notes) {
  if (Array.isArray(value)) return `readonly ${value.every((v) => typeof v === 'string') ? 'string' : 'unknown'}[]`;
  if (value === null) return 'null';
  if (typeof value !== 'object') return typeof value;
  const pad = '  '.repeat(indent + 1);
  const rows = [];
  for (const [key, inner] of Object.entries(value)) {
    const note = notes[`${path}.${key}`] ?? notes[path.replace(/^color\.(light|dark)$/, 'color.*') + `.${key}`];
    if (note) rows.push(`${pad}/** ${note} */`);
    const name = /^[A-Za-z_$][\w$]*$/.test(key) ? key : JSON.stringify(key);
    rows.push(`${pad}readonly ${name}: ${typeOf(inner, indent + 1, `${path}.${key}`, notes)};`);
  }
  return `{\n${rows.join('\n')}\n${'  '.repeat(indent)}}`;
}

export function tokensTypes(model, version) {
  const { values, notes } = moduleData(model, version);
  const lines = [`// Types of tokens/tokens.mjs, NCode Brand ${version}. Generated by build.mjs; do not edit it.`, ''];
  for (const [name, value] of Object.entries(values)) {
    lines.push(`/** ${DOCS[name]} */`, `export declare const ${name}: ${typeOf(value, 0, name, notes)};`, '');
  }
  return lines.join('\n');
}
