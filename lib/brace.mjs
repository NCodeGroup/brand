// Writes brace/: the brace drawn from the construction of the NCode mark's brace, straight stems and circular arcs,
// with hooks at the ends and a cusp in the middle whose tip is half the stroke high.
//
//   brace-mark.svg        the mark's own left brace: a fixed shape, 12 by 48 of its 64 units
//   brace-{sm,md,lg}.svg  a left brace that takes any height: the hooks and the cusp keep their size and only the
//                         stems stretch, because the pieces are anchored at 0, 50% and 100% of an SVG with no viewBox
//   brace.json            the same geometry as data, for a component that draws the brace inline
//
// A right brace is the same file mirrored. base.css uses the files as CSS masks, so a brace takes any color.
import { bracePieces, braceSizes } from './model.mjs';
import { leftBrace } from './logo.mjs';

const n = (value) => Number(value.toFixed(3));
const LAP = 0.5; // the stems reach half a pixel into the hooks and the cusp, so no seam shows where the pieces meet

function stretchable(spec) {
  const p = bracePieces(spec);
  const width = Math.ceil(p.width);
  return `<svg xmlns="http://www.w3.org/2000/svg" width="${width}" height="100%">
  <defs>
    <clipPath id="a"><rect x="0" y="${n(p.ro - LAP)}" width="${width}" height="100000"/></clipPath>
    <clipPath id="b"><rect x="0" y="0" width="${width}" height="100%" transform="translate(0 ${n(-p.ro + LAP)})"/></clipPath>
  </defs>
  <path d="${p.top}"/>
  <g clip-path="url(#a)"><rect x="${n(p.xl)}" y="0" width="${n(spec.w)}" height="50%" transform="translate(0 ${n(-p.k + LAP)})"/></g>
  <svg y="50%" overflow="visible"><path d="${p.cusp}"/></svg>
  <g clip-path="url(#b)"><rect x="${n(p.xl)}" y="50%" width="${n(spec.w)}" height="50%" transform="translate(0 ${n(p.k - LAP)})"/></g>
  <svg y="100%" overflow="visible"><path d="${p.bottom}"/></svg>
</svg>
`;
}

/** Every file of brace/, by its name. */
export function braceFiles(model, logo, version) {
  const markPath = leftBrace(logo.MASTER).path();
  const files = {
    'brace-mark.svg': `<svg xmlns="http://www.w3.org/2000/svg" viewBox="4 8 12 48" width="12" height="48"><path d="${markPath}"/></svg>\n`,
  };
  const sizes = braceSizes(model);
  for (const size of sizes) files[`brace-${size.name}.svg`] = stretchable(size.spec);
  files['brace.json'] = `${JSON.stringify({
    $description:
      `The brace of NCode Brand ${version}, as data. "mark" is the mark's own left brace on its 64-unit grid. Each other size ` +
      'stretches: draw "top" at the top, "cusp" with its origin at the middle and "bottom" with its origin at the ' +
      'bottom, and join them with a stem "stem.width" wide at "stem.x", which runs the rest of the height. Every number ' +
      'is in pixels. A right brace is the left one mirrored. Generated by build.mjs from src/tokens.source.json.',
    mark: { viewBox: '4 8 12 48', width: 12, height: 48, d: markPath },
    ...Object.fromEntries(sizes.map((size) => {
      const p = bracePieces(size.spec);
      return [size.name, {
        note: size.note,
        stroke: size.spec.w,
        hookRadius: size.spec.r,
        cuspRadius: size.spec.c,
        hookEnd: size.spec.e,
        width: size.width,
        minHeight: size.minHeight,
        stem: { x: p.xl, width: size.spec.w, hookReach: p.ro, cuspReach: p.k },
        top: p.top,
        cusp: p.cusp,
        bottom: p.bottom,
      }];
    })),
  }, null, 2)}\n`;
  return files;
}
