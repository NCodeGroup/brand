// Writes tokens/tokens.json in the Design Tokens Community Group format, version 2025.10
// (https://www.designtokens.org/tr/2025.10/format/). What the format cannot hold, such as a token's two themes, a
// derivation rule, a width or an em, is in $extensions["org.ncode.instrument"], which tools must preserve.
import { hexToRgb } from './color.mjs';
import {
  PREFIX, braceSizes, defaultInputs, entries, isThemed, noteOf, pick, refName, resolveColors, roleExtras, ruleToCss, valueOf,
} from './model.mjs';

export const EXT = 'org.ncode.instrument';

function dtcgColor(resolved) {
  const alpha = /^rgb\((\d+) (\d+) (\d+) \/ ([0-9.]+)\)$/.exec(resolved);
  if (alpha) {
    const rgb = alpha.slice(1, 4).map(Number);
    return {
      colorSpace: 'srgb',
      components: rgb.map((v) => Number((v / 255).toFixed(4))),
      alpha: Number(alpha[4]),
      hex: `#${rgb.map((v) => v.toString(16).padStart(2, '0')).join('')}`,
    };
  }
  return { colorSpace: 'srgb', components: hexToRgb(resolved).map((v) => Number(v.toFixed(4))), hex: resolved.toLowerCase() };
}

const tier = (name) => ({ $extensions: { [EXT]: { tier: name } } });

export function toDtcg(model, version) {
  const { base, semantic } = model.source;
  const describe = (token, note) => (note ? { ...token, $description: note } : token);
  const defaults = defaultInputs(model);
  const out = {
    $schema: 'https://www.designtokens.org/schemas/2025.10/format.json',
    $description:
      `${model.source.name}: the design tokens of NCode's look and feel, NCode Brand ${version}. Generated by build.mjs from ` +
      'src/tokens.source.json; do not edit it. Primitives are at the top level. The semantic colors and shadows are under ' +
      '"light" and "dark", resolved for NCode\'s own brand; a token a tenant\'s colors change carries its rule in ' +
      '$extensions. A group that sets a tier names it in its $extensions, and the groups inside it inherit it: "semantic" ' +
      'is the public contract, "primitive" is private.',
    $extensions: {
      [EXT]: {
        version,
        prefix: PREFIX,
        modes: { light: '#/light', dark: '#/dark' },
        tenantInputs: Object.fromEntries(model.inputs.map((i) => [i.name, { css: `${PREFIX}${i.name}`, default: defaults[i.name], rule: i.rule, description: i.note }])),
      },
    },
  };

  out.color = { $type: 'color', ...tier('primitive') };
  for (const [name, ramp] of Object.entries(model.ramps)) {
    out.color[name] = { $description: ramp.note };
    for (const [step, { hex, anchor }] of Object.entries(ramp.steps)) out.color[name][step] = describe({ $value: dtcgColor(hex) }, anchor);
  }

  const group = (type, source, map, extra = {}) => {
    const ext = { ...(extra.$extensions?.[EXT] ?? {}), tier: source.$tier };
    const result = { ...(type ? { $type: type } : {}), ...(source.$note ? { $description: source.$note } : {}), $extensions: { [EXT]: ext } };
    for (const [name, entry] of entries(source)) result[name] = describe({ $value: map(valueOf(entry), entry) }, noteOf(entry));
    return result;
  };
  const font = base.font;
  out.font = {
    family: group('fontFamily', font.family, (v) => v),
    width: group('number', font.width, (v) => v, { $extensions: { [EXT]: { unit: '%', css: 'font-stretch' } } }),
    weight: group('fontWeight', font.weight, (v) => v),
    size: group('dimension', font.size, (v) => ({ value: v, unit: 'rem' })),
    leading: group('number', font.leading, (v) => v),
    tracking: group('number', font.tracking, (v) => v, { $extensions: { [EXT]: { unit: 'em', css: 'letter-spacing' } } }),
  };
  out.space = group('dimension', base.space, (v) => ({ value: v, unit: 'rem' }));
  out.radius = group('dimension', base.radius, (v) => ({ value: v, unit: 'px' }));
  out.border = group('dimension', base.border, (v) => ({ value: v, unit: 'px' }));
  out.size = { $type: 'dimension', ...tier(base.size.$tier) };
  for (const [name, entry] of entries(base.size)) out.size[name] = describe({ $value: { value: entry.value, unit: entry.unit } }, entry.note);
  out.breakpoint = group('dimension', base.breakpoint, (v) => ({ value: v, unit: 'rem' }));
  out.duration = group('duration', { ...base.motion.duration, $tier: base.motion.$tier }, (v) => ({ value: v, unit: 'ms' }));
  out.easing = { $type: 'cubicBezier', $extensions: { [EXT]: { tier: base.motion.$tier } } };
  for (const [name, entry] of entries(base.motion.easing)) {
    if (entry.type === 'cubicBezier') out.easing[name] = describe({ $value: entry.value }, entry.note);
    else out.easing.$extensions[EXT][name] = { css: entry.value, description: entry.note }; // steps() has no token type
  }
  out.brace = {
    $description: base.brace.$note,
    $extensions: { [EXT]: { tier: base.brace.$tier, ...Object.fromEntries(entries(base.brace).map(([name, spec]) => [name, spec])) } },
  };
  for (const size of braceSizes(model)) {
    out.brace[size.name] = describe(
      { $type: 'dimension', $value: { value: size.width, unit: 'px' } },
      `the width of the ${size.name} brace${size.note ? `: ${size.note}` : ''}`,
    );
  }

  out.typography = { $type: 'typography', $description: semantic.type.$note, ...tier(semantic.type.$tier) };
  for (const [name, role] of entries(semantic.type)) {
    const width = pick(font.width, role.width);
    const tracking = pick(font.tracking, role.tracking);
    const { stretch, tracking: trackingCss } = roleExtras(role);
    out.typography[name] = describe(
      {
        $value: {
          fontFamily: `{font.family.${role.family}}`,
          fontSize: typeof role.size === 'string' ? `{font.size.${role.size}}` : { value: role.size, unit: 'rem' },
          fontWeight: typeof role.weight === 'string' ? `{font.weight.${role.weight}}` : role.weight,
          // A DTCG letter spacing is a dimension in px or rem; the em value is in $extensions.
          letterSpacing: { value: Number((tracking * pick(font.size, role.size)).toFixed(4)), unit: 'rem' },
          lineHeight: pick(font.leading, role.leading),
        },
        $extensions: {
          [EXT]: {
            fontStretch: `${width}%`,
            letterSpacing: `${tracking}em`,
            ...(role.case ? { textTransform: role.case } : {}),
            css: `${PREFIX}type-${name}`,
            cssStretch: { property: `${PREFIX}type-${name}-stretch`, value: stretch },
            cssTracking: { property: `${PREFIX}type-${name}-tracking`, value: trackingCss },
          },
        },
      },
      role.note,
    );
  }

  for (const theme of ['light', 'dark']) {
    const resolved = resolveColors(model, theme);
    const colors = { $type: 'color' };
    for (const token of model.colors) {
      const rule = isThemed(token.rule) ? token.rule[theme] : token.rule;
      const ref = refName(rule);
      let value;
      if (ref && !ref.startsWith('color.') && !ref.startsWith('brand')) value = `{color.${ref}}`; // a ramp step
      else if (ref && ref.startsWith('color.')) value = `{${theme}.color.${ref.slice(6)}}`;
      else value = dtcgColor(resolved[token.name]);
      const derivedFrom = /brand-secondary/.test(JSON.stringify(token.rule)) ? `${PREFIX}brand-secondary` : `${PREFIX}brand`;
      const ext = token.brand
        ? { css: `${PREFIX}color-${token.name}`, derivedFrom, rule: ruleToCss(model, token.rule) }
        : { css: `${PREFIX}color-${token.name}` };
      colors[token.name] = describe({ $value: value, $extensions: { [EXT]: ext } }, token.note);
    }
    const shadows = { $type: 'shadow', $description: semantic.elevation.$note };
    for (const [name, layers] of entries(semantic.elevation)) {
      shadows[name] = {
        $value: layers.map((layer) => {
          const px = (v) => ({ value: typeof v === 'string' ? base.size[refName(v)].value : v, unit: 'px' });
          return {
            color: `{${theme}.color.${refName(layer.color).slice(6)}}`,
            offsetX: px(layer.x),
            offsetY: px(layer.y),
            blur: px(layer.blur),
            spread: px(layer.spread ?? 0),
            ...(layer.inset ? { inset: true } : {}),
          };
        }),
        $extensions: { [EXT]: { css: `${PREFIX}elevation-${name}` } },
      };
    }
    out[theme] = {
      $description: `Semantic tokens, ${theme} theme, for NCode's own brand.`,
      ...tier(semantic.color.$tier),
      color: colors,
      shadow: shadows,
    };
  }
  return out;
}
